  '불':   { color: '#f08a2a' },
  '흙':   { color: '#a87a4a' },   // 토기 (신석기부터)
  '청동': { color: '#5aa88a' },   // 청동기부터
  '철':   { color: '#5a6a8a' },   // 철기·가야부터
